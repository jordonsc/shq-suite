void test_active_zone_setpoint_picks_array_by_mode() {
  ControllerState s;
  TEST_ASSERT_TRUE(feed(s, LIVING_HEAT_PAGE1, sizeof(LIVING_HEAT_PAGE1)));
  TEST_ASSERT_TRUE(feed(s, LIVING_HEAT_PAGE2, sizeof(LIVING_HEAT_PAGE2)));

  // Mode is HEAT, so active zone setpoints come from the heat array
  TEST_ASSERT_EQUAL_HEX16(0x00DC, state::activeZoneSetpoint(s, 0));
  TEST_ASSERT_EQUAL_HEX16(0x00F0, state::activeZoneSetpoint(s, 5));

  // Force the state into OFF — active zone setpoint should be SENTINEL_NONE (not applicable)
  s.mode = Mode::Off;
  TEST_ASSERT_EQUAL_HEX16(SENTINEL_NONE, state::activeMasterSetpoint(s));
  TEST_ASSERT_EQUAL_HEX16(SENTINEL_NONE, state::activeZoneSetpoint(s, 0));

  // In COOL mode, picks the cool array
  s.mode = Mode::Cool;
  TEST_ASSERT_EQUAL_HEX16(0x00E6, state::activeZoneSetpoint(s, 0));
  TEST_ASSERT_EQUAL_HEX16(s.cool_main_setpoint_raw, state::activeMasterSetpoint(s));

  // In AUTO mode, picks cool array as the canonical single-field display
  s.mode = Mode::Auto;
  TEST_ASSERT_EQUAL_HEX16(0x00E6, state::activeZoneSetpoint(s, 0));
  TEST_ASSERT_EQUAL_HEX16(s.cool_main_setpoint_raw, state::activeMasterSetpoint(s));
}

void test_zone_enable_mask_change_decodes() {
  ControllerState s;
  TEST_ASSERT_TRUE(feed(s, LIVING_HEAT_PAGE1, sizeof(LIVING_HEAT_PAGE1)));
  // After first frame: mask 0x01 (Living-only)
  TEST_ASSERT_EQUAL_HEX8(0x01, s.zone_enable_mask);
  TEST_ASSERT_TRUE(s.zones[0].enabled);
  TEST_ASSERT_FALSE(s.zones[1].enabled);

  // Second frame: Living disabled, Entry now the only enabled zone
  TEST_ASSERT_TRUE(feed(s, ZONE_LIVING_DISABLED_PAGE1, sizeof(ZONE_LIVING_DISABLED_PAGE1)));
  TEST_ASSERT_EQUAL_HEX8(0x02, s.zone_enable_mask);
  TEST_ASSERT_FALSE(s.zones[0].enabled);
  TEST_ASSERT_TRUE(s.zones[1].enabled);
}

void test_unchanged_frame_returns_false() {
  ControllerState s;
  TEST_ASSERT_TRUE(feed(s, LIVING_HEAT_PAGE1, sizeof(LIVING_HEAT_PAGE1)));
  // Feeding the same page-1 again should change nothing and return false
  TEST_ASSERT_FALSE(feed(s, LIVING_HEAT_PAGE1, sizeof(LIVING_HEAT_PAGE1)));
}

void test_mode_and_fan_name_roundtrip() {
  TEST_ASSERT_EQUAL_STRING("heat", state::modeName(Mode::Heat));
  TEST_ASSERT_EQUAL_STRING("auto", state::modeName(Mode::Auto));
  TEST_ASSERT_EQUAL((int)Mode::Cool, (int)state::parseMode("cool"));
  TEST_ASSERT_EQUAL((int)Mode::Unknown, (int)state::parseMode("blast"));
  TEST_ASSERT_EQUAL_STRING("low", state::fanName(FanSpeed::Low));
  TEST_ASSERT_EQUAL((int)FanSpeed::Auto, (int)state::parseFan("auto"));
}

