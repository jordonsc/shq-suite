// ---- helpers --------------------------------------------------------------

static bool feed(ControllerState& s, const uint8_t* frame, size_t len) {
  return state::feedNeoFrame(s, frame, len);
}

// ---- tests ---------------------------------------------------------------

void test_rejects_non_neo_addr() {
  ControllerState s;
  std::vector<uint8_t> f(LIVING_HEAT_PAGE1, LIVING_HEAT_PAGE1 + sizeof(LIVING_HEAT_PAGE1));
  f[0] = 0x67;  // change addr → no longer a NEO frame
  uint16_t c = bridge::crc16(f.data(), f.size() - 2);
  f[f.size() - 2] = (uint8_t)(c & 0xFF);
  f[f.size() - 1] = (uint8_t)(c >> 8);
  TEST_ASSERT_FALSE(feed(s, f.data(), f.size()));
  TEST_ASSERT_FALSE(s.page1_seen);
  TEST_ASSERT_EQUAL(Mode::Unknown, (int)s.mode);
}

void test_rejects_wrong_func() {
  ControllerState s;
  std::vector<uint8_t> f(LIVING_HEAT_PAGE1, LIVING_HEAT_PAGE1 + sizeof(LIVING_HEAT_PAGE1));
  f[1] = 0x10;  // write-multiple func code
  uint16_t c = bridge::crc16(f.data(), f.size() - 2);
  f[f.size() - 2] = (uint8_t)(c & 0xFF);
  f[f.size() - 1] = (uint8_t)(c >> 8);
  TEST_ASSERT_FALSE(feed(s, f.data(), f.size()));
}

void test_rejects_unknown_bytecount() {
  ControllerState s;
  uint8_t f[] = {0x66, 0x03, 0x10, 0x00, 0x01, 0x00, 0x00};  // bytecount 0x10, not F8/F4
  // Trailing two bytes are garbage CRC — but the unknown bytecount should also fail the
  // expected-length check first.
  TEST_ASSERT_FALSE(feed(s, f, sizeof(f)));
}

void test_rejects_corrupt_crc() {
  ControllerState s;
  std::vector<uint8_t> f(LIVING_HEAT_PAGE1, LIVING_HEAT_PAGE1 + sizeof(LIVING_HEAT_PAGE1));
  f[f.size() - 1] ^= 0xFF;  // flip the CRC high byte
  TEST_ASSERT_FALSE(feed(s, f.data(), f.size()));
  TEST_ASSERT_FALSE(s.page1_seen);
}

void test_page1_decodes_living_heat() {
  ControllerState s;
  TEST_ASSERT_TRUE(feed(s, LIVING_HEAT_PAGE1, sizeof(LIVING_HEAT_PAGE1)));
  TEST_ASSERT_TRUE(s.page1_seen);

  // Mode word reg 10 = 0x8082 → mode bits = 2 = HEAT
  TEST_ASSERT_EQUAL_HEX16(0x8082, s.mode_word_raw);
  TEST_ASSERT_EQUAL((int)Mode::Heat, (int)s.mode);

  // Fan word reg 11 = 0x5904 → speed bits = 4 = AUTO, cont-fan bit 7 = 0
  TEST_ASSERT_EQUAL_HEX16(0x5904, s.fan_word_raw);
  TEST_ASSERT_EQUAL((int)FanSpeed::Auto, (int)s.fan);
  TEST_ASSERT_FALSE(s.continuous_fan);

  // Active main setpoint reg 12 = 0x00EB = 23.5
  TEST_ASSERT_EQUAL_HEX16(0x00EB, s.main_setpoint_raw);

  // Main/return-air temp reg 13 = 0x00D7 = 21.5 (matches the lone enabled zone here)
  TEST_ASSERT_EQUAL_HEX16(0x00D7, s.main_temp_raw);

  // Cool main store reg 55 = 0x00E6 (23.0); heat main store reg 56 = 0x00EB (23.5)
  TEST_ASSERT_EQUAL_HEX16(0x00E6, s.cool_main_setpoint_raw);
  TEST_ASSERT_EQUAL_HEX16(0x00EB, s.heat_main_setpoint_raw);
  // In HEAT mode, activeMasterSetpoint == heat store
  TEST_ASSERT_EQUAL_HEX16(0x00EB, state::activeMasterSetpoint(s));

  // Zone enable mask reg 85 = 0x0001 → only Living enabled
  TEST_ASSERT_EQUAL_HEX8(0x01, s.zone_enable_mask);
  TEST_ASSERT_TRUE(s.zones[0].enabled);
  for (size_t i = 1; i < state::NUM_ZONES; i++) TEST_ASSERT_FALSE(s.zones[i].enabled);

  // Live zone temps reg 94–101 read directly from the capture bytes
  // (capture's commentary block had transcribed values; raw bytes are authoritative):
  // 21.5 / 19.6 / 21.8 / 21.0 / 19.7 / 24.4 / 21.5 / 21.5
  TEST_ASSERT_EQUAL_HEX16(0x00D7, s.zones[0].current_temp_raw);  // 21.5
  TEST_ASSERT_EQUAL_HEX16(0x00C4, s.zones[1].current_temp_raw);  // 19.6
  TEST_ASSERT_EQUAL_HEX16(0x00DA, s.zones[2].current_temp_raw);  // 21.8
  TEST_ASSERT_EQUAL_HEX16(0x00D2, s.zones[3].current_temp_raw);  // 21.0
  TEST_ASSERT_EQUAL_HEX16(0x00C5, s.zones[4].current_temp_raw);  // 19.7
  TEST_ASSERT_EQUAL_HEX16(0x00F4, s.zones[5].current_temp_raw);  // 24.4
  TEST_ASSERT_EQUAL_HEX16(0x00D7, s.zones[6].current_temp_raw);  // 21.5
  TEST_ASSERT_EQUAL_HEX16(0x00D7, s.zones[7].current_temp_raw);  // 21.5
}

